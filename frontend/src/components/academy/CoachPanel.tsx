'use client';

import { Loader2, MessageCircleQuestion, Sparkles } from 'lucide-react';
import type { CoachResponse } from '@/types/learn';

const LEVEL_NAMES = ['Nudge', 'Concept', 'Pattern'] as const;

interface CoachPanelProps {
  hints: CoachResponse[];
  loading: boolean;
  onAsk: () => void;
}

export function CoachPanel({ hints, loading, onAsk }: CoachPanelProps) {
  const nextLevel = hints.length + 1;
  const exhausted = hints.length >= 3;

  return (
    <div className="glass-card rounded-xl p-4">
      <div className="flex items-center justify-between gap-3">
        <div>
          <h3 className="flex items-center gap-1.5 text-sm font-semibold text-white">
            <MessageCircleQuestion className="h-4 w-4 text-amber-400" /> Granite coach
          </h3>
          <p className="mt-0.5 text-[12px] text-[#666]">
            Hints escalate from a nudge to a concrete pattern. The coach never writes the prompt for you.
          </p>
        </div>
        <button
          type="button"
          onClick={onAsk}
          disabled={loading || exhausted}
          className="shrink-0 rounded-lg border border-amber-500/20 bg-amber-500/5 px-3 py-1.5 text-[12px] font-medium text-amber-300 transition-colors hover:bg-amber-500/10 disabled:opacity-40"
        >
          {loading ? (
            <Loader2 className="h-3.5 w-3.5 animate-spin" />
          ) : exhausted ? (
            'All hints used'
          ) : (
            `Hint ${nextLevel}/3: ${LEVEL_NAMES[nextLevel - 1]}`
          )}
        </button>
      </div>

      {hints.length > 0 && (
        <ol className="mt-4 space-y-3">
          {hints.map((h) => (
            <li key={h.hint_level} className="rounded-lg border border-amber-500/10 bg-amber-500/[0.03] p-3">
              <p className="mb-1.5 flex items-center gap-1.5 text-[10px] font-semibold uppercase tracking-wider text-amber-400/80">
                Level {h.hint_level} · {LEVEL_NAMES[h.hint_level - 1]}
                {h.source === 'granite' && <Sparkles className="h-3 w-3" aria-label="Generated by Granite" />}
              </p>
              <p className="text-[12px] text-[#888]">{h.diagnosis}</p>
              <p className="mt-1.5 text-[13px] leading-relaxed text-[#ddd]">{h.hint}</p>
              {h.question && <p className="mt-1.5 text-[12px] italic text-amber-200/70">{h.question}</p>}
            </li>
          ))}
        </ol>
      )}
    </div>
  );
}
