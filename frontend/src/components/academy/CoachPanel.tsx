'use client';

import { Loader2, Sparkles } from 'lucide-react';
import type { CoachResponse } from '@/types/learn';
import { cn } from '@/lib/utils';

const LEVELS = [
  { name: 'Nudge', body: 'Points at where the problem is.' },
  { name: 'Concept', body: 'Names the technique and why it fixes this.' },
  { name: 'Pattern', body: 'Shows the shape of a fix, never the full prompt.' },
] as const;

interface CoachPanelProps {
  hints: CoachResponse[];
  loading: boolean;
  onAsk: () => void;
  hasAttempt: boolean;
}

export function CoachPanel({ hints, loading, onAsk, hasAttempt }: CoachPanelProps) {
  const exhausted = hints.length >= 3;
  const next = LEVELS[hints.length];

  return (
    <div>
      <p className="text-sm leading-relaxed text-fg-muted">
        The Granite coach reads your prompt and your latest test results, then gives a hint. Hints escalate in three
        levels. It will never write the prompt for you.
      </p>

      {/* Ladder */}
      <ol className="mt-5 grid grid-cols-3 gap-2">
        {LEVELS.map((l, i) => (
          <li
            key={l.name}
            className={cn(
              'rounded-lg border px-3 py-2',
              i < hints.length ? 'border-[rgba(241,194,27,0.35)] bg-warn-soft' : 'border-line'
            )}
          >
            <p className={cn('text-xs font-medium', i < hints.length ? 'text-warn' : 'text-fg-muted')}>
              {i + 1}. {l.name}
            </p>
            <p className="mt-0.5 text-[11px] leading-snug text-fg-subtle">{l.body}</p>
          </li>
        ))}
      </ol>

      <button
        type="button"
        onClick={onAsk}
        disabled={loading || exhausted}
        className="mt-4 inline-flex h-9 items-center gap-2 rounded-lg border border-[rgba(241,194,27,0.35)] px-4 text-sm text-warn transition-colors hover:bg-warn-soft disabled:opacity-40"
      >
        {loading && <Loader2 className="h-3.5 w-3.5 animate-spin" />}
        {exhausted ? 'All hints used' : `Get hint ${hints.length + 1}: ${next.name}`}
      </button>
      {!hasAttempt && !exhausted && (
        <p className="mt-2 text-xs text-fg-subtle">Tip: run your prompt first so the coach can see what failed.</p>
      )}

      {hints.length > 0 && (
        <div className="mt-6 space-y-3">
          {hints.map((h) => (
            <article key={h.hint_level} className="rounded-lg border border-line bg-raised p-4">
              <p className="flex items-center gap-1.5 text-xs font-medium text-warn">
                Level {h.hint_level} · {LEVELS[h.hint_level - 1].name}
                {h.source === 'granite' && <Sparkles className="h-3 w-3" aria-label="Generated by Granite" />}
              </p>
              <p className="mt-2 text-[13px] text-fg-subtle">{h.diagnosis}</p>
              <p className="mt-2 text-sm leading-relaxed text-fg">{h.hint}</p>
              {h.question && <p className="mt-2 text-[13px] italic text-fg-muted">{h.question}</p>}
            </article>
          ))}
        </div>
      )}
    </div>
  );
}
